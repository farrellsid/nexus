// Fetch the fonts the shell uses and host them locally, so the page never contacts Google.
//
//   node scripts/nexus-fetch-fonts.mjs
//
// Google's CSS API returns @font-face rules whose src is a subsetted woff2 on fonts.gstatic.com.
// This script downloads those files once into public/fonts/, records their SHA-256, and writes
// src/ui/styles/fonts.css with local @font-face rules. Only the latin and latin-ext subsets of
// the text fonts are kept. The CSS request uses a current browser User-Agent because that is how
// the API decides to serve woff2; it is an ordinary font request, not a workaround for any block.
// Licences: Inter (SIL OFL 1.1), JetBrains Mono (SIL OFL 1.1), Material Symbols (Apache-2.0).
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';
const TEXT = 'https://fonts.googleapis.com/css2?family=JetBrains+Mono:wght@300;400;500;600;700&family=Inter:wght@300;400;500;600&display=swap';
const ICONS = process.argv[2] ?? '';
const KEEP = new Set(['latin', 'latin-ext']);

const get = async (url, asBytes = false) => {
  const response = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!response.ok) throw new Error(`${response.status} for ${url}`);
  return asBytes ? Buffer.from(await response.arrayBuffer()) : response.text();
};

const fontsDir = join(root, 'public', 'fonts');
mkdirSync(fontsDir, { recursive: true });
const manifest = [];
const rules = [];
const iconRules = []; // the icon class must load after the app stylesheet, as Google's did

async function localise(css, { keepAll, family }) {
  const blocks = [...css.matchAll(/(?:\/\*\s*([\w-]+)\s*\*\/\s*)?@font-face\s*\{([^}]*)\}/g)];
  for (const [, subset, body] of blocks) {
    if (!keepAll && !KEEP.has(subset)) continue;
    const src = /url\((https:[^)]+)\)\s*format\('woff2'\)/.exec(body)?.[1];
    if (!src) continue;
    const weight = /font-weight:\s*([^;]+);/.exec(body)?.[1].trim() ?? '400';
    const style = /font-style:\s*([^;]+);/.exec(body)?.[1].trim() ?? 'normal';
    const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1].trim();
    const bytes = await get(src, true);
    const sha = createHash('sha256').update(bytes).digest('hex');
    // Variable fonts arrive as one identical file per weight; keep one copy per distinct content.
    const file = `${family.toLowerCase().replace(/\s+/g, '-')}-${subset ?? 'icon-subset'}-${sha.slice(0, 8)}.woff2`;
    if (!manifest.some((f) => f.file === file)) {
      writeFileSync(join(fontsDir, file), bytes);
      manifest.push({ file, family, subset: subset ?? 'icon-subset', bytes: bytes.length, sha256: sha, from: src.replace(/kit=[^&]+/, 'kit=...') });
    }
    rules.push(
      `@font-face {\n  font-family: '${family}';\n  font-style: ${style};\n  font-weight: ${weight};\n  font-display: swap;\n  src: url('/fonts/${file}') format('woff2');${range ? `\n  unicode-range: ${range};` : ''}\n}`,
    );
  }
}

const textCss = await get(TEXT);
for (const family of ['Inter', 'JetBrains Mono']) {
  const own = [...textCss.matchAll(/(?:\/\*\s*[\w-]+\s*\*\/\s*)?@font-face\s*\{[^}]*\}/g)]
    .map((m) => m[0])
    .filter((block) => block.includes(`font-family: '${family}'`))
    .join('\n');
  await localise(own.replace(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face/g, '/* $1 */ @font-face'), { keepAll: false, family });
}
if (ICONS) {
  const iconCss = await get(ICONS);
  await localise(iconCss, { keepAll: true, family: 'Material Symbols Outlined' });
  // The API also returns the class that turns the glyph name into an icon (ligatures on).
  const iconClass = /\.material-symbols-outlined\s*\{[^}]*\}/.exec(iconCss)?.[0];
  if (iconClass) iconRules.push(iconClass);
}

mkdirSync(join(root, 'src', 'ui', 'styles'), { recursive: true });
writeFileSync(
  join(root, 'src', 'ui', 'styles', 'fonts.css'),
  `/* Generated by scripts/nexus-fetch-fonts.mjs. Local copies of Inter and JetBrains Mono (SIL OFL 1.1)\n   and a Material Symbols Outlined glyph subset (Apache-2.0). The page must not contact Google. */\n${rules.join('\n')}\n`,
);
writeFileSync(
  join(root, 'src', 'ui', 'styles', 'icon-glyphs.css'),
  `/* Generated by scripts/nexus-fetch-fonts.mjs. Imported LAST in style.css: the icon class came from Google's\n   stylesheet, which loaded after the app's, so its 24px size won ties with app rules. Keep that order. */\n${iconRules.join('\n')}\n`,
);
writeFileSync(join(fontsDir, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`${manifest.length} font files, ${(manifest.reduce((n, f) => n + f.bytes, 0) / 1024).toFixed(0)} KB`);
for (const f of manifest) console.log(`  ${f.file}  ${f.bytes} bytes  sha256 ${f.sha256.slice(0, 12)}`);
