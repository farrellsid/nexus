// Generate src/nexus/oilStops.ts from the oil investigation's sourced geography and evidence pack.
//
//   node scripts/generate-oil-stops.mjs          write the file
//   node scripts/generate-oil-stops.mjs --check  exit 1 when the file is not what the source produces
//
// The stops and routes are evidence-pack data (investigations/02-oil-system/geography.json), so the
// shell reads a generated copy rather than a hand-typed one. Field names become camelCase; nothing
// is added, rounded or reordered. From the evidence pack only the summary the readouts need is
// copied: which pack, when it was checked, and its entity list (so the shell can say how many
// entities have no anchor on the map).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as prettier from 'prettier';

const here = dirname(fileURLToPath(import.meta.url));
const sourcePath = resolve(here, '../../../investigations/02-oil-system/geography.json');
const packPath = resolve(here, '../../../investigations/02-oil-system/evidence-pack.json');
const targetPath = join(here, '../src/nexus/oilStops.ts');

const camel = (key) => key.replace(/_([a-z])/g, (_, letter) => letter.toUpperCase());
const convert = (value) =>
  Array.isArray(value)
    ? value.map(convert)
    : value && typeof value === 'object'
      ? Object.fromEntries(Object.entries(value).map(([key, inner]) => [camel(key), convert(inner)]))
      : value;

export function renderOilStops(source, pack) {
  const geography = convert(source);
  const packSummary = convert({
    case_id: pack.case_id,
    schema_version: pack.schema_version,
    checked_on: pack.checked_on,
    scope: pack.scope,
    entities: pack.entities.map(({ id, name, type }) => ({ id, name, type })),
  });
  return `// Generated by scripts/generate-oil-stops.mjs from investigations/02-oil-system/geography.json.
// Do not edit by hand: change the source and regenerate. \`npm run check:generated\` fails on drift.

/** A sourced label anchor for guided reading. Never a boundary, route or vessel position. */
export interface OilStop {
  readonly id: string;
  readonly entityId: string;
  readonly label: string;
  readonly latitude: number;
  readonly longitude: number;
  readonly precision: string;
  readonly role: string;
  readonly whyItMatters: string;
  readonly caveat: string;
  readonly sourceTitle: string;
  readonly sourceUrl: string;
  readonly checkedOn: string;
}

/** A sourced illustrative line built from anchor-point coordinates. */
export interface OilRoute {
  readonly id: string;
  readonly entityId: string;
  readonly label: string;
  readonly points: readonly { readonly latitude: number; readonly longitude: number }[];
  readonly precision: string;
  readonly role: string;
  readonly whyItMatters: string;
  readonly caveat: string;
  readonly sourceTitle: string;
  readonly sourceUrl: string;
  readonly checkedOn: string;
}

export interface OilGeography {
  readonly title: string;
  readonly framing: string;
  readonly stops: readonly OilStop[];
  readonly routes: readonly OilRoute[];
}

export const OIL_GEOGRAPHY: OilGeography = ${JSON.stringify(geography, null, 2)};

/** What the evidence pack is and which of its entities exist; the readouts count against this. */
export interface OilPackSummary {
  readonly caseId: string;
  readonly schemaVersion: string;
  readonly checkedOn: string;
  readonly scope: string;
  readonly entities: readonly { readonly id: string; readonly name: string; readonly type: string }[];
}

export const OIL_PACK: OilPackSummary = ${JSON.stringify(packSummary, null, 2)};
`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const raw = renderOilStops(JSON.parse(readFileSync(sourcePath, 'utf8')), JSON.parse(readFileSync(packPath, 'utf8')));
  const options = { ...(await prettier.resolveConfig(targetPath)), parser: 'typescript' };
  const generated = await prettier.format(raw, options);
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(targetPath, 'utf8').replaceAll('\r\n', '\n');
    } catch {
      /* a missing file counts as drift */
    }
    if (current !== generated) {
      console.error('src/nexus/oilStops.ts is out of date: run node scripts/generate-oil-stops.mjs');
      process.exit(1);
    }
    console.log('src/nexus/oilStops.ts matches geography.json and evidence-pack.json');
  } else {
    writeFileSync(targetPath, generated);
    console.log(`wrote ${targetPath}`);
  }
}
